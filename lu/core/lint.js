import { normalizeLesson, estimateMinutes } from './session.js';
import { kiemHanhDong } from './hanh-dong.js';
import { kiemTimBong } from './tim-bong.js';
import { kiemCheckin } from './checkin.js';
// Quality Gate tự động cho một gói bài (LU_PRODUCT_QUALITY_STANDARD mục 13). Chạy được cả trong trình duyệt và Node.
// errors: chặn duyệt và xuất bản. warnings: người duyệt xem lại.
export const FORBID = ['ngốc', 'phạt', 'thông minh', 'IQ', 'EQ', 'giỏi hơn bạn', 'thua', 'kém cỏi'];
const LABEL = /(con|bé|bạn|cháu)\s+(\S+\s+)?(hư|dở|chậm|kém|lười)([^\p{L}]|$)/iu;
const EN_WORDS = /\b(the|is|are|yes|no|well|done|hello|let's|good|great|excellent|oops|wow|you|it|this|my|and)\b/i;
const EMOJI = /(?![©®™])\p{Extended_Pictographic}/u;
const TECH = /(undefined|null|\bNaN\b|TODO|lorem|placeholder|\bJSON\b|\bAPI\b|prompt|token|debug|Generated by|ChatGPT|Claude|ComfyUI|Stable Diffusion)/i;
const SKIP_KEYS = new Set(['activity_id', 'lesson_id', 'skill_id', 'engine', 'mechanic', 'mode', 'style', 'step', 'content_version', 'review_status', 'format', 'vi_tri', 'c', 'cls', 'audio', 'target_style', 'order', 'note', 'art', 'manifest', 'way']);
const PRAISE_LABEL = /(con|bé)\s+(\S+\s+)?(ngoan|chăm|thông minh|tài)\s*(quá|thế|lắm)?([^\p{L}]|$)/iu;
// S07-R02 (26/11/2026): lời nói với trẻ gọi "bé", không gọi "con". "con" đứng trước tên con vật/đồ vật vẫn hợp lệ.
const CON_VERB = 'chạm|kéo|chọn|nghe|nói|làm|đếm|tìm|thấy|nhìn|thử|đi|ngồi|đứng|vươn|lắc|nhớ|muốn|có|đã|đang|sẽ|giúp|xem|lật|ghép|xếp|hít|thở|kể|cùng|ơi|nhé|học|quay|được|biết|hãy|ạ|ra|vào|đặt|nhảy|vỗ|giơ|hỏi|chơi|mở|so|chỉ|đọc|viết|vẽ|tô|gieo|thả|bấm|giữ|lên|xuống|là|thích|ôm';
const CON_ADDR = new RegExp(`(^|[.!?:]\\s*)con\\s+(${CON_VERB})([^\\p{L}]|$)|(chào|cùng|của|cho|với|nhờ|mời|khen|giúp|cảm ơn|đợi|chờ|đón)\\s+con([^\\p{L}]|$)|(^|[^\\p{L}])(?<!(gà|vịt|mèo|chó|lợn|heo|bò|trâu|chim|cá|ếch|thỏ|ngựa|dê|voi|gấu|khỉ|ong|bướm|sâu|ốc)\\s)con\\s+(${CON_VERB})([^\\p{L}]|$)`, 'iu'); // "gà con sẽ…" là tên con vật, không phải gọi trẻ
const SELF_TO = /(^|[^\p{L}])(tớ|cậu)([^\p{L}]|$)/iu;
const EN_ACT = a => a.mode === 'listen' || a.mode === 'say' || /^EN\./.test(a.skill_id || '');

function walk(o, fn, key = '', path = '') {
  if (typeof o === 'string') return fn(o, key, path);
  if (Array.isArray(o)) return o.forEach((x, i) => walk(x, fn, key, `${path}[${i}]`));
  if (o && typeof o === 'object') for (const [k, v] of Object.entries(o)) if (!SKIP_KEYS.has(k)) walk(v, fn, k, path ? `${path}.${k}` : k);
}

export function lintLesson(pkg, skills = null) {
  const errors = [], warnings = [];
  const check = (obj, where, english) => walk(obj, (s, key, path) => {
    const at = `${where}${path ? ' › ' + path : ''}`;
    if (EMOJI.test(s)) errors.push(`${at}: dùng emoji "${s.slice(0, 20)}". Thay bằng hình đã duyệt (art:…, face:…, asset:…)`);
    if (TECH.test(s) && !s.startsWith('asset:')) errors.push(`${at}: có chữ kỹ thuật hoặc chỗ trống chưa điền: "${s.slice(0, 40)}"`);
    for (const w of FORBID) if (new RegExp(`(^|[^\\p{L}])${w}([^\\p{L}]|$)`, 'iu').test(s)) errors.push(`${at}: có từ không dùng với trẻ "${w}"`);
    if (LABEL.test(s)) errors.push(`${at}: gắn nhãn tiêu cực cho trẻ`);
    if (!english && EN_WORDS.test(s) && !/[àáảãạăâđèéẻẽẹêìíỉĩịòóỏõọôơùúủũụưỳýỷỹỵ]/i.test(s) && s.split(' ').length > 1) warnings.push(`${at}: câu tiếng Anh nằm trong phần tiếng Việt`);
    if (PRAISE_LABEL.test(s)) warnings.push(`${at}: khen bằng nhãn về con người "${s.slice(0, 40)}"; khen cụ thể việc bé vừa làm (S07-PL1)`);
    if (SELF_TO.test(s)) warnings.push(`${at}: xưng hô "tớ/cậu"; gọi trẻ là "bé", dùng "mình" khi cùng làm (S07-R02)`);
    if (!/^parent|^why|^goal/.test(path) && CON_ADDR.test(s)) errors.push(`${at}: gọi trẻ là "con" trong "${s.slice(0, 50)}"; đổi thành "bé" (S07-R02, sửa 26/11)`);
    if (s.length > 140) warnings.push(`${at}: câu dài ${s.length} ký tự, nên tách cho trẻ dễ nghe`);
  });
  pkg = normalizeLesson(pkg);
  const { activities = [], skills: sk = [], stages: _st, ...rest } = pkg;
  if (_st) _st.forEach((st, i) => check({ title: st.title }, `Chặng ${i + 1}`, false));
  check(rest, 'Bài', false);
  activities.forEach(a => check(a, a.activity_id || 'hoạt động', EN_ACT(a)));
  // Giáo dục
  if (skills) for (const s of sk) if (!skills[s.skill_id]) errors.push(`Skill ${s.skill_id} không có trong Skill Tree`);
  if (!pkg.goal && !pkg.parent?.goal) warnings.push('Bài chưa ghi mục tiêu cho bố mẹ (parent.goal)');
  // Đa dạng trải nghiệm
  const engines = new Set(activities.map(a => a.engine));
  if (activities.length >= 3 && engines.size < 2) warnings.push('Cả bài chỉ dùng một kiểu trò chơi; nên có ít nhất 2 engine');
  // Lời khen không lặp
  const praise = {}; walk(activities, (s, k) => { if (k === 'ok' || k === 'done') praise[s] = (praise[s] || 0) + 1; });
  for (const [s, n] of Object.entries(praise)) if (n > 2) warnings.push(`Lời khen "${s}" lặp ${n} lần`);
  // Buổi học nhiều chặng (D42, S02-R02)
  if (pkg.stages) {
    const est = estimateMinutes(pkg); const n = pkg.stages.length;
    const minPhut = /^M/.test(pkg.lesson_id || '') ? 15 : 20; /* buổi Mono: 10 bài × 3 lượt ≈ 16 phút màn hình + 5 phút cùng bố mẹ (chờ sếp chốt 27/11) */
    if (est.minutes < minPhut) errors.push(`Buổi học ước tính ${est.minutes} phút, cần ít nhất ${minPhut} phút (S02-R02)`);
    if (pkg.layout === 'hub') { if (n < 12 || n > 16) warnings.push(`Trang buổi học có ${n} bài nhỏ, chuẩn là 12–16 (D46)`); }
    else if (n < 10 || n > 12) warnings.push(`Buổi có ${n} chặng, chuẩn là 10–12 (S02-R02)`);
    // D45: mỗi buổi phủ đủ 13 nhóm năng lực bằng bài nhỏ thật (khai báo trong stage.nhom là rèn TRỰC TIẾP)
    const NHOM13 = ['TD', 'QS', 'CY', 'GN', 'NT', 'TTg', 'EN', 'TV', 'TO', 'EQ', 'KT', 'KS', 'ST'];
    const has = new Set(pkg.stages.flatMap(st => st.nhom || []));
    const miss = NHOM13.filter(c => !has.has(c));
    if (miss.length) (pkg.lesson_id === 'MAU' ? warnings : errors).push(`Buổi thiếu nhóm năng lực có hoạt động thật: ${miss.join(', ')} (D45)`);
    pkg.stages.forEach((st, i) => { if (!st.nhom?.length) warnings.push(`Bài nhỏ ${i + 1} chưa khai báo nhóm năng lực (D45)`); if (!st.thiet_ke) warnings.push(`Bài nhỏ ${i + 1} chưa có phần thiết kế (kiến thức, hành động, bằng chứng, giới hạn) (D45)`); });
    const ways = new Set(pkg.stages.map(st => st.way).filter(Boolean));
    if (ways.size < 6) errors.push(`Buổi chỉ có ${ways.size} cách truyền đạt, cần ít nhất 6 (S02-R02)`);
    if (!pkg.stages.some(st => st.way === 'van-dong')) errors.push('Buổi thiếu chặng vận động (S02-R02)');
    pkg.stages.forEach((st, i) => { if (!st.backdrop) warnings.push(`Chặng ${i + 1} chưa có bối cảnh (S04-R13)`); });
  }
  // Quy tắc 38 (tam 27/11): hỏi hành động thì đáp án là ảnh hành động của chính nhân vật được hỏi
  errors.push(...kiemHanhDong(activities));
  // Quy tắc 39 (tam 27/11): bài tìm bóng hiện ảnh bóng to giữa màn, hỏi "Cái bóng này là của ảnh nào dưới đây?"
  errors.push(...kiemTimBong(activities));
  // Quy tắc 44 (tam 27/11 13:03): bài tìm vật đặt vật rải rác trên cảnh thật, không xếp ô thẻ
  activities.forEach(a => { if (a.engine === 'E06' && !a.mode && a.layout !== 'roi') errors.push(`${a.activity_id || a.title}: bài tìm vật phải đặt vật rải rác trên cảnh vườn (layout "roi", bg), không xếp ô thẻ (quy tắc 44)`); });
  // Quy tắc 40 (tam 27/11): hỏi cảm xúc đầu buổi chỉ đọc câu hỏi, Lu đáp theo mặt bé chọn
  errors.push(...kiemCheckin(pkg.checkin));
  // Hình phải có trong kho và đã duyệt
  walk(pkg, (s) => { if (s.startsWith('asset:')) warnings.push(`Kiểm tra tài nguyên ${s.slice(6)} đã duyệt trong Asset Registry`); });
  return { errors: [...new Set(errors)], warnings: [...new Set(warnings)] };
}
